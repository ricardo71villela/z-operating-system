// Z Jobs portal — interface texts. Launch scope: France, Belgium,
// Luxembourg; French ("vous") and English. French is the default.
//
// t(key, params) reads the language set by setMessagesLocale(), which the
// portal calls on every render, so plain helper components can use it too.

export const LOCALES = [
  { code: 'fr', label: 'FR' },
  { code: 'en', label: 'EN' },
];

const STORAGE_KEY = 'zjobs_locale';
let current = 'fr';

export function setMessagesLocale(locale) {
  current = MESSAGES[locale] ? locale : 'fr';
}

export function messagesLocale() {
  return current;
}

/** ?lang=, then the last choice, then the browser language; French otherwise. */
export function initialLocale() {
  try {
    const asked = new URLSearchParams(window.location.search).get('lang');
    const saved = window.localStorage.getItem(STORAGE_KEY);
    const browser = (navigator.language || '').slice(0, 2).toLowerCase();
    const locale = asked || saved || (browser === 'en' ? 'en' : 'fr');
    return MESSAGES[locale] ? locale : 'fr';
  } catch {
    return 'fr';
  }
}

export function rememberLocale(locale) {
  try { window.localStorage.setItem(STORAGE_KEY, locale); } catch { /* storage unavailable */ }
}

export function t(key, params) {
  const template = (MESSAGES[current] && MESSAGES[current][key]) ?? MESSAGES.fr[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in params ? String(params[name]) : `{${name}}`));
}

/** Number formatting for amounts (1 867 in French, 1,867 in English). */
export function formatAmount(n) {
  return new Intl.NumberFormat(current === 'en' ? 'en-GB' : 'fr-FR', { minimumFractionDigits: 0 }).format(n);
}

