#!/usr/bin/env python3
"""Builds the Z Jobs reference locations (France, Belgium, Luxembourg) as SQL.

Inputs (pinned, official or derived from official sources):
  --fr  data dir of the npm package @etalab/decoupage-administratif@6.0.0
        (Etalab / INSEE Code officiel géographique: communes, départements)
  --be  data dir of the npm package belgica@0.5.0
        (Statbel REFNIS municipalities and postal-code conversion table, CC BY 4.0)
  --lu  apps/jobs/tools/locations/lu_communes.csv (100 communes and their canton)

Scope (v1): every Belgian and Luxembourg commune; French communes with at least
--fr-min-population inhabitants (default 1000: about 10 000 communes, 87 % of the
population). Smaller communes can be added later with coordinates for radius search.

Usage:
  npm pack @etalab/decoupage-administratif@6.0.0 belgica@0.5.0   # then untar each
  python3 -I build_locations_sql.py --fr <etalab>/package/data --be <belgica>/package/data \
      --lu lu_communes.csv --out-dir infrastructure/supabase/migrations

Writes three files small enough for the Supabase SQL editor (run them in order):
  20261022210000_z_jobs_locations_1_schema_be_lu_v1.sql
  20261022210100_z_jobs_locations_2_fr_a_v1.sql
  20261022210200_z_jobs_locations_3_fr_b_v1.sql
"""
import argparse
import csv
import json
import re
import unicodedata
from pathlib import Path


def search_key(*names: str) -> str:
    """Lower case, no accents, punctuation as spaces: what the API compares against."""
    out = []
    for name in names:
        if not name:
            continue
        s = unicodedata.normalize("NFKD", name)
        s = "".join(c for c in s if not unicodedata.combining(c)).lower()
        s = re.sub(r"[^a-z0-9]+", " ", s).strip()
        if s and s not in out:
            out.append(s)
    return " | ".join(out)


def q(v):
    if v is None:
        return "null"
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def france(data: Path, min_population: int):
    deps = {d["code"]: d["nom"] for d in json.loads((data / "departements.json").read_text())}
    rows = []
    for c in json.loads((data / "communes.json").read_text()):
        if c.get("type") != "commune-actuelle":
            continue
        pop = c.get("population") or 0
        if pop < min_population:
            continue
        postal = sorted(c.get("codesPostaux") or [None])[0]
        dep = c.get("departement")
        admin = f"{deps.get(dep, dep)} ({dep})" if dep else None
        rows.append(("FR", f"FR-{c['code']}", c["nom"], None, admin, postal, pop, search_key(c["nom"])))
    return rows


def belgium(data: Path):
    provinces = {p["id"]: p["name"] for p in json.loads((data / "provinces.json").read_text())}
    regions = {r["id"]: r["name"] for r in json.loads((data / "regions.json").read_text())}
    postal = {}
    for p in json.loads((data / "postal-codes.json").read_text()):
        postal.setdefault(p["municipality"], []).append(p["postalCode"])
    rows = []
    for m in json.loads((data / "municipalities.json").read_text()):
        names = m["name"]
        fr, nl, de = names.get("fr"), names.get("nl"), names.get("de")
        city = fr or nl or de
        alt = nl if nl and nl != city else (de if de and de != city else None)
        area = provinces.get(m.get("province")) or regions.get(m.get("region")) or {}
        admin = area.get("fr") or area.get("nl")
        code = sorted(postal.get(m["id"], [None]))[0]
        rows.append(("BE", f"BE-{m['id']}", city, alt, admin, code, None, search_key(city, nl, de)))
    return rows


def luxembourg(path: Path):
    lines = [l for l in path.read_text().splitlines() if l and not l.startswith("#")]
    rows = []
    for r in csv.DictReader(lines):
        slug = search_key(r["commune"]).replace(" ", "-")
        rows.append(("LU", f"LU-{slug}", r["commune"], None, f"Canton de {r['canton']}" if r["canton"][0] not in "AEIOUÉ" else f"Canton d'{r['canton']}", None, None, search_key(r["commune"])))
    return rows


HEADER = """-- Z Jobs — reference locations for the launch countries (France, Belgium, Luxembourg), part 1 of 3
--
-- Generated by apps/jobs/tools/locations/build_locations_sql.py — do not edit by hand.
-- Sources:
--   France: Etalab / INSEE Code officiel géographique via @etalab/decoupage-administratif@6.0.0
--           (communes with at least {fr_min} inhabitants: {fr_n} rows)
--   Belgium: Statbel REFNIS municipalities and postal-code table via belgica@0.5.0, CC BY 4.0
--           ({be_n} municipalities, main postal code = lowest code of the municipality)
--   Luxembourg: the 100 communes and their canton ({lu_n} rows)
--
-- Idempotent: safe to run again (upsert on country_code + official_code).

begin;

-- 1. Launch countries (locations.country_code references countries.code,
--    countries.default_currency references currencies.code).
insert into jobs.currencies (code, name) values ('EUR', 'Euro')
on conflict (code) do nothing;
insert into jobs.locales (code, name) values ('fr', 'Français'), ('en', 'English')
on conflict (code) do nothing;
insert into jobs.countries (code, name, default_locale, default_currency) values
  ('FR', 'France', 'fr-FR', 'EUR'),
  ('BE', 'Belgique', 'fr-BE', 'EUR'),
  ('LU', 'Luxembourg', 'fr-LU', 'EUR')
on conflict (code) do update set name = excluded.name, is_active = true;

-- 2. Reference columns.
alter table jobs.locations add column if not exists official_code text;
alter table jobs.locations add column if not exists alt_name text;
alter table jobs.locations add column if not exists population integer;
alter table jobs.locations add column if not exists search_key text;
create unique index if not exists locations_country_official_code_key
  on jobs.locations (country_code, official_code) where official_code is not null;
create index if not exists idx_locations_search_key on jobs.locations (country_code, search_key);

-- 3. The API reads these reference tables (no writes needed).
alter table jobs.countries enable row level security;
alter table jobs.locations enable row level security;
drop policy if exists countries_select_all on jobs.countries;
create policy countries_select_all on jobs.countries for select using (true);
drop policy if exists locations_select_all on jobs.locations;
create policy locations_select_all on jobs.locations for select using (true);
grant select on jobs.countries, jobs.locations to jobs_runtime;

-- 4. Data (Luxembourg and Belgium here; France in parts 2 and 3).
"""

PART = """-- Z Jobs — reference locations, part {n} of 3: {what}
-- Generated by apps/jobs/tools/locations/build_locations_sql.py — run after part 1.

begin;

"""

FOOTER = """
commit;

-- Check: expected {total} rows ({fr_n} FR, {be_n} BE, {lu_n} LU).
-- select country_code, count(*) from jobs.locations where official_code is not null group by 1 order by 1;
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fr", type=Path, required=True)
    ap.add_argument("--be", type=Path, required=True)
    ap.add_argument("--lu", type=Path, required=True)
    ap.add_argument("--fr-min-population", type=int, default=1000)
    ap.add_argument("--out-dir", type=Path, required=True)
    a = ap.parse_args()

    fr, be, lu = france(a.fr, a.fr_min_population), belgium(a.be), luxembourg(a.lu)
    assert len(lu) == 100, len(lu)
    counts = dict(fr_min=a.fr_min_population, fr_n=len(fr), be_n=len(be), lu_n=len(lu), total=len(fr) + len(be) + len(lu))
    cols = "(country_code, official_code, city, alt_name, admin_area, postal_code, population, search_key)"

    def inserts(label, rows):
        out = []
        for i in range(0, len(rows), 1000):
            chunk = rows[i:i + 1000]
            values = ",\n".join("  (" + ", ".join(q(v) for v in r) + ")" for r in chunk)
            out.append(
                f"-- {label} {i + 1}–{i + len(chunk)}\n"
                f"insert into jobs.locations {cols} values\n{values}\n"
                "on conflict (country_code, official_code) where official_code is not null do update set\n"
                "  city = excluded.city, alt_name = excluded.alt_name, admin_area = excluded.admin_area,\n"
                "  postal_code = excluded.postal_code, population = excluded.population, search_key = excluded.search_key;\n"
            )
        return "\n".join(out)

    half = (len(fr) + 1) // 2
    files = [
        ("20261022210000_z_jobs_locations_1_schema_be_lu_v1.sql", HEADER.format(**counts) + inserts("Luxembourg", lu) + "\n" + inserts("Belgium", be) + "\ncommit;\n"),
        ("20261022210100_z_jobs_locations_2_fr_a_v1.sql", PART.format(n=2, what=f"France, communes 1–{half} (by INSEE code)") + inserts("France", fr[:half]) + "\ncommit;\n"),
        ("20261022210200_z_jobs_locations_3_fr_b_v1.sql", PART.format(n=3, what=f"France, communes {half + 1}–{len(fr)}") + inserts("France", fr[half:]) + FOOTER.format(**counts)),
    ]
    for suffix, sql in files:
        path = a.out_dir / suffix
        path.write_text(sql)
        print(f"{path} ({path.stat().st_size // 1024} KB)")
    print(f"FR {len(fr)} · BE {len(be)} · LU {len(lu)}")

if __name__ == "__main__":
    main()
